ALTER TABLE required_channels ALTER COLUMN channel_username DROP NOT NULL;
ALTER TABLE required_channels ADD COLUMN IF NOT EXISTS chat_id      character varying(64);
ALTER TABLE required_channels ADD COLUMN IF NOT EXISTS title        character varying(255);
ALTER TABLE required_channels ADD COLUMN IF NOT EXISTS invite_link  character varying(255);
-- true bo'lsa, foydalanuvchi kanalga zayavka yuborganining o'zi yetarli
ALTER TABLE required_channels ADD COLUMN IF NOT EXISTS join_request boolean NOT NULL DEFAULT false;
ALTER TABLE required_channels ADD COLUMN IF NOT EXISTS created_at   timestamp(6) without time zone;
-- bo'sh bo'lsa, muddatsiz
ALTER TABLE required_channels ADD COLUMN IF NOT EXISTS expires_at   timestamp(6) without time zone;

CREATE UNIQUE INDEX IF NOT EXISTS required_channels_chat_id_key ON required_channels (chat_id);

-- Bot orqali kanalga qo'shilgan (yoki zayavka yuborgan) foydalanuvchilar.
-- Bitta odam bir kanal uchun bir marta sanaladi. Kanal o'chirilsa, yozuvlari ham o'chadi.
CREATE TABLE IF NOT EXISTS channel_joins (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id  bigint                         NOT NULL REFERENCES required_channels (id) ON DELETE CASCADE,
    user_id     bigint                         NOT NULL,
    via_request boolean                        NOT NULL DEFAULT false,
    created_at  timestamp(6) without time zone NOT NULL,
    CONSTRAINT channel_joins_channel_user_key UNIQUE (channel_id, user_id)
);
