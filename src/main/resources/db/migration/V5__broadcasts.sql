-- Reklamalar: darhol yoki belgilangan vaqtda yuboriladi, natijalari saqlanadi.
-- Xabarning o'zi saqlanmaydi: admin chatidagi asl xabardan nusxa olinadi (source_*).
CREATE TABLE IF NOT EXISTS broadcasts (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by        bigint                         NOT NULL,
    source_chat_id    bigint                         NOT NULL,
    source_message_id integer                        NOT NULL,
    button_text       character varying(64),
    button_url        character varying(512),
    send_at           timestamp(6) without time zone NOT NULL,
    -- SCHEDULED, SENDING, DONE, CANCELLED, INTERRUPTED
    status            character varying(32)          NOT NULL,
    total             integer                        NOT NULL DEFAULT 0,
    sent              integer                        NOT NULL DEFAULT 0,
    blocked           integer                        NOT NULL DEFAULT 0,
    failed            integer                        NOT NULL DEFAULT 0,
    created_at        timestamp(6) without time zone NOT NULL,
    started_at        timestamp(6) without time zone,
    finished_at       timestamp(6) without time zone
);

CREATE INDEX IF NOT EXISTS broadcasts_status_send_at_idx ON broadcasts (status, send_at);
